class Fixture(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.exe = Path('/sdk/idea/bin/idea')
        self.idea = Path('/sdk/idea')
        self.env = {'PATH': '/usr/sbin:/usr/bin', 'LC_ALL': 'C'}
        self.calls = []
        for value in ('/etc/apparmor.d/abi', '/etc/apparmor.d/tunables', '/etc/apparmor.d/local',
                      '/var/cache/apparmor', '/usr/sbin', '/usr/bin'):
            (self.root / value.lstrip('/')).mkdir(parents=True, exist_ok=True)
        self.write(profile.CONFIG, b'# fixture default config\n')
        self.write(profile.INVENTORY, b'other-policy (enforce)\n')
        self.write('/etc/apparmor.d/abi/4.0', b'policy { versions { v8 { yes } } }\n')
        self.write('/etc/apparmor.d/tunables/global', b'# fixture tunables\n')
        self.write('/usr/sbin/apparmor_parser', b'synthetic parser, not executable code', 0o755)
        self.write('/usr/bin/dpkg-query', b'synthetic query, not executable code', 0o755)
        md5 = hashlib.md5(b'synthetic parser, not executable code', usedforsecurity=False).hexdigest()
        self.write('/var/lib/dpkg/info/apparmor.md5sums', f'{md5}  usr/sbin/apparmor_parser\n'.encode())
        pins = {}
        class_hashes = {profile.GENERATOR_CLASS: profile._sha(GENERATOR),
                        profile.NAMES_CLASS: profile._sha(NAMES)}
        for name, member, data in ((profile.GENERATOR_JAR, profile.GENERATOR_CLASS, GENERATOR),
                                   (profile.CORE_JAR, profile.NAMES_CLASS, NAMES)):
            path = self.local(self.idea / name)
            path.parent.mkdir(parents=True, exist_ok=True)
            with zipfile.ZipFile(path, 'w') as archive:
                archive.writestr(member, data)
            raw = path.read_bytes()
            pins[name] = (len(raw), profile._sha(raw))
        for name in ('bin/idea', 'jbr/bin/java'):
            raw = ('synthetic ' + name).encode()
            self.write(self.idea / name, raw, 0o755)
            pins[name] = (len(raw), profile._sha(raw))
        # Simulate root ownership without chown or privilege. Real mode checks
        # remain active; trust's actual owner rejection has separate fixtures.
        original_trust = profile._trust
        original_alias_trust = profile._trust_distro_alias
        def synthetic_root(info, directory=False):
            return original_trust(SimpleNamespace(st_uid=0, st_mode=info.st_mode), directory)
        def synthetic_root_alias(info):
            return original_alias_trust(SimpleNamespace(st_uid=0, st_mode=info.st_mode))
        for target, replacement in (('_trust', synthetic_root), ('PINNED', pins),
                                    ('CLASS_HASHES', class_hashes), ('_trust_distro_alias', synthetic_root_alias)):
            p = patch.object(profile, target, replacement)
            p.start()
            self.addCleanup(p.stop)
        p = patch.object(profile.os, 'geteuid', return_value=0)
        p.start()
        self.addCleanup(p.stop)

    def local(self, value):
        return self.root / str(value).lstrip('/')

    def write(self, value, raw, mode=0o644):
        path = self.local(value)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
        path.chmod(mode)
        return path

    def runner(self, command, **kwargs):
        self.calls.append((command, kwargs))
        if command[0] == '/usr/bin/dpkg-query':
            output = b'install ok installed\t4.0.1-0ubuntu0.24.04.4\tamd64\n'
        elif command[1:] == ['--version']:
            output = b'AppArmor parser version 4.0.1\nCopyright fixture\n'
        elif command[1:] == ['--print-config-file', '--version']:
            output = b'/etc/apparmor/parser.conf\nAppArmor parser version 4.0.1\nCopyright fixture\n'
        elif command[1:] == ['--print-cache-dir']:
            output = b'/var/cache/apparmor/synthetic-feature\n'
        elif command[1:] == ['-n', '-l']:
            output = b'Matching Defaults entries for fixture:\n    secure_path=/usr/sbin:/usr/bin\nUser may run:\n    (ALL : ALL) NOPASSWD: ALL\n'
        else:
            self.fail('unexpected fixture command')
        return subprocess.CompletedProcess(command, 0, stdout=output)

    def prepare(self, **changes):
        return profile.prepare(self.exe, self.idea, runner=changes.pop('runner', self.runner),
                               env=changes.pop('env', self.env), filesystem_root=self.root, **changes)

    def before(self, candidate, **changes):
        return profile.recheck_before(candidate, self.exe, env=self.env, filesystem_root=self.root, **changes)

    def install_fixture(self, candidate):
        self.write(candidate['destination'], candidate['expected_utf8'].encode())
        self.write(profile.INVENTORY, f'{self.exe} (unconfined)\n'.encode())

    def installed(self, candidate):
        return profile.verify_installed(candidate, env=self.env, filesystem_root=self.root)

    def error(self, code, function, *args, **kwargs):
        with self.assertRaises(profile.ProfileError) as caught:
            function(*args, **kwargs)
        self.assertEqual(caught.exception.code, code)
        self.assertEqual(str(caught.exception), code)
        self.assertIs(type(caught.exception.step), str)
        self.assertIn(caught.exception.step, profile.STEPS)
        return caught.exception


