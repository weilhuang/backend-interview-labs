    def test_exact_sudo_identity_handshake_precedes_only_the_managed_probe(self):
        self.write('/usr/bin/xterm', b'fixture terminal', 0o755)
        self.write('/usr/bin/sudo', b'fixture sudo', 0o4755)
        fixture = self
        class ManagedRunner:
            def __init__(self):
                self.expected = None
                self.events = []
            def expect_sudo_probe(self, helper):
                fixture.assertIsNone(self.expected)
                self.expected = copy.deepcopy(helper)
                self.events.append(('EXPECT_SUDO', copy.deepcopy(helper)))
                # The handshake receives a copy; it cannot mutate the private
                # candidate's verified on-disk identity through this argument.
                helper['identity'][0] = -1
            def run(self, command, **kwargs):
                if command == ['/usr/bin/sudo', '-n', '-l']:
                    fixture.assertIsNotNone(self.expected)
                    fixture.assertEqual(self.expected['path'], command[0])
                    self.expected = None
                    self.events.append(('SUDO_PROBE', command))
                else:
                    fixture.assertIsNone(self.expected)
                return fixture.runner(command, **kwargs)
        managed = ManagedRunner()
        with patch.object(profile.os, 'geteuid', return_value=1000):
            candidate = self.prepare(runner=managed.run)
        helpers = candidate['parser']['expected_helpers']
        self.assertEqual(set(helpers), {'TERMINAL', 'SUDO'})
        for helper in helpers.values():
            self.assertEqual(set(helper), {'path', 'identity', 'sha256'})
